import React, { useState } from 'react';
import { X, Copy, Check, Printer, FileText } from 'lucide-react';
import { DecisionAnalysisResult } from '../types/decision';

interface ExportModalProps {
  isOpen: boolean;
  onClose: () => void;
  decisionTitle: string;
  analysis: DecisionAnalysisResult;
  committedOption?: string;
}

export const ExportModal: React.FC<ExportModalProps> = ({
  isOpen,
  onClose,
  decisionTitle,
  analysis,
  committedOption,
}) => {
  const [copied, setCopied] = useState(false);

  if (!isOpen) return null;

  const generateMarkdown = () => {
    let md = `# Decision Record: ${decisionTitle}\n\n`;
    md += `**Date:** ${new Date().toLocaleDateString()}\n`;
    md += `**Dilemma Type:** ${analysis.dilemmaType}\n`;
    if (committedOption) {
      md += `**Committed Final Choice:** ${committedOption}\n`;
    }
    md += `\n---\n\n`;
    md += `## Executive Summary\n${analysis.summary}\n\n`;

    md += `## The Tiebreaker Verdict: ${analysis.verdict.recommendedOption}\n`;
    md += `*Confidence: ${analysis.verdict.confidencePercentage}%*\n\n`;
    md += `> "${analysis.verdict.headline}"\n\n`;
    md += `**The Decisive Tiebreaker Factor:**\n${analysis.verdict.decisiveFactor}\n\n`;
    md += `**Strategic Rationale:**\n${analysis.verdict.detailedVerdict}\n\n`;

    md += `### Reversal Conditions (When to choose alternative options)\n`;
    analysis.verdict.reversalConditions.forEach(rc => {
      md += `- **Choose "${rc.optionName}" IF:** ${rc.condition}\n`;
    });
    md += `\n`;

    md += `### The 10/10/10 Mental Model\n`;
    md += `- **In 10 Minutes:** ${analysis.verdict.tenTenTenRule.tenMinutes}\n`;
    md += `- **In 10 Months:** ${analysis.verdict.tenTenTenRule.tenMonths}\n`;
    md += `- **In 10 Years:** ${analysis.verdict.tenTenTenRule.tenYears}\n\n`;

    md += `### Pre-Mortem Safeguard\n`;
    md += `**Failure Scenario:** ${analysis.verdict.preMortem.failureScenario}\n\n`;
    md += `**Preventive Action:** ${analysis.verdict.preMortem.preventiveAction}\n\n`;

    md += `## Pros & Cons Breakdown\n\n`;
    analysis.optionsAnalysis.forEach(opt => {
      md += `### ${opt.name} — *"${opt.tagline}"*\n`;
      md += `**Pros:**\n`;
      opt.pros.forEach(p => {
        md += `- [Weight ${p.weight}/5] **${p.title}** (${p.category}): ${p.description}\n`;
      });
      md += `\n**Cons:**\n`;
      opt.cons.forEach(c => {
        md += `- [Weight ${c.weight}/5] **${c.title}** (${c.category}): ${c.description}\n`;
      });
      md += `\n`;
    });

    md += `## SWOT Analysis Matrix\n\n`;
    analysis.optionsAnalysis.forEach(opt => {
      md += `### SWOT: ${opt.name}\n`;
      md += `- **Strengths:** ${opt.swot.strengths.join('; ')}\n`;
      md += `- **Weaknesses:** ${opt.swot.weaknesses.join('; ')}\n`;
      md += `- **Opportunities:** ${opt.swot.opportunities.join('; ')}\n`;
      md += `- **Threats:** ${opt.swot.threats.join('; ')}\n\n`;
    });

    md += `---\n*Generated by The Tiebreaker AI Decision Engine*`;
    return md;
  };

  const markdownText = generateMarkdown();

  const handleCopy = () => {
    navigator.clipboard.writeText(markdownText);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handlePrint = () => {
    window.print();
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center bg-slate-950/80 p-4 backdrop-blur-md">
      <div className="w-full max-w-3xl max-h-[85vh] rounded-2xl border border-slate-800 bg-slate-900 shadow-2xl flex flex-col overflow-hidden animate-in zoom-in-95">
        {/* Header */}
        <div className="flex items-center justify-between border-b border-slate-800 p-5">
          <div className="flex items-center space-x-2">
            <FileText className="h-5 w-5 text-indigo-400" />
            <h3 className="font-bold text-white text-base">Export Decision Memo</h3>
          </div>
          <button
            onClick={onClose}
            className="rounded-lg p-1.5 text-slate-400 hover:text-white hover:bg-slate-800 transition-colors"
          >
            <X className="h-5 w-5" />
          </button>
        </div>

        {/* Preview Area */}
        <div className="flex-1 overflow-y-auto p-5">
          <div className="rounded-xl border border-slate-800 bg-slate-950 p-4 font-mono text-xs text-slate-300 whitespace-pre-wrap select-all max-h-[50vh] overflow-y-auto">
            {markdownText}
          </div>
        </div>

        {/* Actions */}
        <div className="border-t border-slate-800 p-4 flex items-center justify-between">
          <p className="text-xs text-slate-400 hidden sm:block">
            Formatted in standard Markdown for Notion, Obsidian, Slack, or Docs.
          </p>
          <div className="flex items-center space-x-2">
            <button
              onClick={handlePrint}
              className="inline-flex items-center space-x-1.5 rounded-xl border border-slate-700 bg-slate-800 px-3.5 py-2 text-xs font-semibold text-slate-300 hover:bg-slate-700 hover:text-white transition-colors"
            >
              <Printer className="h-3.5 w-3.5" />
              <span>Print / PDF</span>
            </button>
            <button
              onClick={handleCopy}
              className="inline-flex items-center space-x-1.5 rounded-xl bg-emerald-500 px-4 py-2 text-xs font-bold text-slate-950 hover:bg-emerald-400 transition-colors shadow-lg shadow-emerald-500/20"
            >
              {copied ? <Check className="h-3.5 w-3.5" /> : <Copy className="h-3.5 w-3.5" />}
              <span>{copied ? 'Copied to Clipboard!' : 'Copy Markdown'}</span>
            </button>
          </div>
        </div>
      </div>
    </div>
  );
};
